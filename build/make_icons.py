"""Generate the PWA/home-screen icon set into build/pwa/.

One mark, drawn once at high resolution and downsampled for crispness: a
brick-red square with a white map-pin silhouette, echoing the same pin shape
already on the map (a circle plus a tapered tail) so the home-screen icon
reads as "this app" rather than a generic placeholder.

Run once when the icon design changes -- the output is checked in like
geom.json, not regenerated by every build. inject.py copies build/pwa/*
into dist/ on every build; build.sh mirrors dist/ into the repo root for
GitHub Pages alongside index.html.
"""
import math
import os
from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'pwa')
os.makedirs(OUT, exist_ok=True)

BRICK = (166, 51, 40, 255)   # --brick, light-mode value -- fixed regardless of theme
WHITE = (255, 255, 255, 255)

SS = 8  # supersample factor for clean anti-aliased edges


def pin_polygon(cx, cy, r, tail_k=1.85, half_angle_deg=38):
    """Circle (cx,cy,r) fused with a tail so the union is a classic map-pin
    teardrop: the tail's two base vertices sit ON the circle so the straight
    edges meet the curve tangent-ish, with no visible notch."""
    half = math.radians(half_angle_deg)
    ax = cx + r * math.sin(half)
    ay = cy + r * math.cos(half)
    bx = cx - r * math.sin(half)
    by = cy + r * math.cos(half)
    tip_y = cy + r * tail_k
    return [(ax, ay), (cx, tip_y), (bx, by)]


def draw_icon(size, bleed=False, out_name=None):
    """bleed=True fills the full canvas (safe for a circular/rounded-square
    mask -- 'maskable' icons); bleed=False leaves a touch of margin, right
    for iOS/plain favicon use where nothing crops the edges."""
    img = Image.new('RGBA', (size * SS, size * SS), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    S = size * SS
    d.rectangle([0, 0, S, S], fill=BRICK)

    if bleed:
        # keep the glyph inside the ~80% safe-zone circle Android's
        # maskable spec crops to
        cx, cy, r = S * 0.5, S * 0.40, S * 0.155
        tail_k = 1.7
    else:
        cx, cy, r = S * 0.5, S * 0.40, S * 0.225
        tail_k = 1.85

    d.polygon(pin_polygon(cx, cy, r, tail_k), fill=WHITE)
    d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=WHITE)
    # small brick dot in the pin's center, matching the sale pins' hollow look
    hr = r * 0.34
    d.ellipse([cx - hr, cy - hr, cx + hr, cy + hr], fill=BRICK)

    img = img.resize((size, size), Image.LANCZOS)
    path = os.path.join(OUT, out_name or ('icon-%d.png' % size))
    img.save(path)
    print('wrote', path, '(%dx%d)' % (size, size))


draw_icon(180, bleed=False, out_name='apple-touch-icon.png')
draw_icon(192, bleed=False, out_name='icon-192.png')
draw_icon(512, bleed=False, out_name='icon-512.png')
draw_icon(512, bleed=True, out_name='icon-512-maskable.png')
draw_icon(32, bleed=False, out_name='favicon.png')
